function AddUserDialog({
  open,
  defaultRole,
  onClose,
  onCreated,
}: {
  open: boolean
  defaultRole: "super_admin" | "sales_executive"
  onClose: () => void
  onCreated: (u: UserProfile) => void
}) {
  const [form, setForm] = useState<NewUserForm>({ ...EMPTY_FORM, role: defaultRole })
  const [showPassword, setShowPassword] = useState(false)
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState<string | null>(null)

  // Reset when opened
  useEffect(() => {
    if (open) { setForm({ ...EMPTY_FORM, role: defaultRole }); setError(null) }
  }, [open, defaultRole])

  function set(key: keyof NewUserForm, val: string) {
    setForm(p => ({ ...p, [key]: val }))
  }

  async function handleSubmit(e: React.FormEvent) {
    e.preventDefault()
    setLoading(true)
    setError(null)
    try {
      const res = await fetch("/api/admin/users", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(form),
      })
      const json = await res.json()
      if (!res.ok) throw new Error(json.error ?? "Failed to create user")
      onCreated({ ...json.user, phone: form.phone || null, created_at: new Date().toISOString() })
      onClose()
    } catch (err) {
      setError(err instanceof Error ? err.message : "Unknown error")
    } finally {
      setLoading(false)
    }
  }

  const isAdmin = form.role === "super_admin"

  return (
    <Dialog open={open} onOpenChange={v => !v && onClose()}>
      <DialogContent className="max-w-md">
        <DialogHeader>
          <DialogTitle className="flex items-center gap-2">
            {isAdmin
              ? <><Shield className="w-4 h-4" style={{ color: "var(--color-primary)" }} /> Add Super Admin</>
              : <><Briefcase className="w-4 h-4" style={{ color: "var(--color-success)" }} /> Add Sales Executive</>
            }
          </DialogTitle>
          <DialogDescription>
            {isAdmin
              ? "Super admins can see all leads, assign them, and manage the team."
              : "Sales executives will receive assigned leads and fill CRM details."}
          </DialogDescription>
        </DialogHeader>

        <form onSubmit={handleSubmit} className="space-y-4 mt-2">
          {/* Role toggle */}
          <div className="flex rounded-lg overflow-hidden" style={{ border: "1px solid var(--color-border)" }}>
            {(["sales_executive", "super_admin"] as const).map(r => (
              <button
                key={r}
                type="button"
                onClick={() => set("role", r)}
                className="flex-1 py-2 text-xs font-semibold transition-all duration-150"
                style={form.role === r ? {
                  background: r === "super_admin"
                    ? "rgb(194 65 12 / 0.12)"
                    : "rgb(21 128 61 / 0.12)",
                  color: r === "super_admin"
                    ? "var(--color-primary)"
                    : "var(--color-success)",
                } : {
                  background: "transparent",
                  color: "var(--color-muted-foreground)",
                }}
              >
                {r === "super_admin" ? "Super Admin" : "Sales Executive"}
              </button>
            ))}
          </div>

          <div className="space-y-1.5">
            <Label className="text-xs" style={{ color: "var(--color-foreground)" }}>Full Name *</Label>
            <Input
              placeholder="e.g. Team Member"
              value={form.full_name}
              onChange={e => set("full_name", e.target.value)}
              required
              className="h-9 text-sm"
            />
          </div>

          <div className="space-y-1.5">
            <Label className="text-xs" style={{ color: "var(--color-foreground)" }}>Email *</Label>
            <Input
              type="email"
              placeholder="user@company.com"
              value={form.email}
              onChange={e => set("email", e.target.value)}
              required
              className="h-9 text-sm"
            />
          </div>

          <div className="space-y-1.5">
            <Label className="text-xs" style={{ color: "var(--color-foreground)" }}>Phone</Label>
            <Input
              type="tel"
              placeholder="Phone number"
              value={form.phone}
              onChange={e => set("phone", e.target.value)}
              className="h-9 text-sm"
            />
          </div>

          <div className="space-y-1.5">
            <Label className="text-xs" style={{ color: "var(--color-foreground)" }}>Password * (min 8 chars)</Label>
            <div className="relative">
              <Input
                type={showPassword ? "text" : "password"}
                placeholder="Minimum 8 characters"
                value={form.password}
                onChange={e => set("password", e.target.value)}
                required
                minLength={8}
                className="h-9 text-sm pr-9"
              />
              <button
                type="button"
                onClick={() => setShowPassword(p => !p)}
                className="absolute right-2.5 top-1/2 -translate-y-1/2"
                style={{ color: "var(--color-muted-foreground)" }}
              >
                {showPassword ? <EyeOff className="w-4 h-4" /> : <Eye className="w-4 h-4" />}
              </button>
            </div>
          </div>

          {error && (
            <div className="flex items-start gap-2 px-3 py-2.5 rounded-lg text-xs"
              style={{ background: "rgb(185 28 28 / 0.10)", color: "var(--color-destructive)", border: "1px solid rgb(185 28 28 / 0.24)" }}>
              <AlertCircle className="w-3.5 h-3.5 shrink-0 mt-0.5" />
              {error}
            </div>
          )}

          <div className="flex gap-3 pt-1">
            <Button type="button" variant="outline" className="flex-1 h-9" onClick={onClose} disabled={loading}>
              Cancel
            </Button>
            <Button
              type="submit"
              disabled={loading}
              className="flex-1 h-9 gold-gradient font-semibold shadow-gold-sm"
              style={{ color: "var(--color-primary-foreground)" }}
            >
              {loading
                ? <><Loader2 className="w-4 h-4 mr-2 animate-spin" />Creating...</>
                : <><UserPlus className="w-4 h-4 mr-2" />Create User</>
              }
            </Button>
          </div>
        </form>
      </DialogContent>
    </Dialog>
  )
}

